// ── gen-embedded ──────────────────────────────────────────────────────────────
// Scans the built ./dist and generates src/server/embedded.generated.ts: one
// `import … with { type: "file" }` per asset plus a Map<urlPath → bunFilePath>.
// Bun resolves these file-imports to the real path on disk (dev / `bun link`) AND
// embeds them into the standalone executable under `bun build --compile`, so the
// SAME serving code works both ways. Run via `bun run build:embed` after vite build.

import { readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative, sep } from "node:path";

const ROOT = join(import.meta.dir, "..");
const DIST = join(ROOT, "dist");
const OUT_DIR = join(ROOT, "src", "server");
const OUT = join(OUT_DIR, "embedded.generated.ts");

function walk(dir: string, acc: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, acc);
    // Don't embed a previously-compiled binary that lives in dist/.
    else if (name !== "acm") acc.push(p);
  }
  return acc;
}

const files = walk(DIST);
const lines: string[] = [
  "// AUTO-GENERATED by scripts/gen-embedded.ts — do not edit.",
  "// @ts-nocheck",
  "",
];
const entries: string[] = [];
files.forEach((abs, i) => {
  const rel = relative(DIST, abs).split(sep).join("/"); // posix url path
  lines.push(`import f${i} from "../../dist/${rel}" with { type: "file" };`);
  entries.push(`  ["/${rel}", f${i}]`);
});
lines.push(
  "",
  "/** url-path → bun file path (real on disk, embedded in the compiled binary). */",
  "export const EMBEDDED_ASSETS = new Map([",
  entries.join(",\n"),
  "]);",
  "",
);

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT, lines.join("\n"));
console.log(`gen-embedded: embedded ${files.length} asset(s) → ${relative(ROOT, OUT)}`);
