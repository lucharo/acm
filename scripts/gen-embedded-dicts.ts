// ── gen-embedded-dicts ─────────────────────────────────────────────────────────
// Generates src/cli/dicts.generated.ts: four `import … with { type: "file" }`
// statements (en/gb × aff/dic) plus a variant→paths map. Bun resolves these
// file-imports to the real path on disk (dev / `bun link`) AND embeds the bytes into
// the standalone executable under `bun build --compile` — so `acm spell` finds its
// Hunspell dictionaries inside the compiled binary, where node_modules isn't present.
//
// The same idea as scripts/gen-embedded.ts (which embeds the SPA), but for the CLI
// spell path. Run via `bun run build:embed`. The generated file is gitignored and
// imported only from cli.ts (outside the tsc `include`), so its absence in plain
// source mode never breaks typecheck — there, the engine reads node_modules instead.
//
// Absolute paths are used deliberately: `bun build --compile` embeds `type: "file"`
// imports by absolute path (verified), and resolving via createRequire is robust to
// git worktrees (where node_modules lives in the parent checkout).

import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { writeFileSync } from "node:fs";

const req = createRequire(import.meta.url);
const dictFile = (pkg: string, file: string) => join(dirname(req.resolve(pkg)), file);

const enAff = dictFile("dictionary-en", "index.aff");
const enDic = dictFile("dictionary-en", "index.dic");
const gbAff = dictFile("dictionary-en-gb", "index.aff");
const gbDic = dictFile("dictionary-en-gb", "index.dic");

const out = `// AUTO-GENERATED by scripts/gen-embedded-dicts.ts — do not edit.
// @ts-nocheck
import enAff from ${JSON.stringify(enAff)} with { type: "file" };
import enDic from ${JSON.stringify(enDic)} with { type: "file" };
import gbAff from ${JSON.stringify(gbAff)} with { type: "file" };
import gbDic from ${JSON.stringify(gbDic)} with { type: "file" };

/** variant → embedded Hunspell file paths. Real on disk in source/built installs,
 *  embedded inside the \`bun build --compile\` binary; readFileSync reads both. */
export const EMBEDDED_DICTS = {
  us: { aff: enAff, dic: enDic },
  uk: { aff: gbAff, dic: gbDic },
};
`;

writeFileSync(new URL("../src/cli/dicts.generated.ts", import.meta.url), out);
console.log("gen-embedded-dicts: wrote src/cli/dicts.generated.ts (4 dict files)");
